#!/usr/bin/env python3
"""Emit assets/js/brakelawsdata.js from _data/state-brake-laws.json.

WHY A GENERATOR RATHER THAN A COPY IN THE PAGE. The record and the page have to agree, and the
one way to guarantee that is to make one of them. The alternative the site has used elsewhere is
to embed a second copy in the tool's own JS and hold the two together with a test, which works
but leaves two places to edit and one of them is the one that gets forgotten.

The rule the shape enforces is the one that matters here: a state reaches a reader only with the
section it came from and the URL it was read at, and a state whose code has not been read has no
entry at all. A guessed threshold is the one failure this tool cannot afford, because a number
that is too high tells somebody to tow without brakes.

Usage: python3 scripts/build-brake-laws-data.py            # write
       python3 scripts/build-brake-laws-data.py --check    # report drift, write nothing
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "_data" / "state-brake-laws.json"
OUT = ROOT / "assets" / "js" / "brakelawsdata.js"

HEADER = """/* GENERATED by scripts/build-brake-laws-data.py from _data/state-brake-laws.json.
 * Do not edit this file; edit the record and re-run the generator.
 *
 * THE ONE RULE THE SHAPE ENFORCES: every threshold here is quoted from the state's own vehicle
 * code, with the section named and the URL it was read at. A state whose code has not been read
 * has no entry, and the tool says so rather than printing a number it cannot show the source of.
 * A threshold that is too high tells a reader to tow without brakes, which is the one failure
 * this tool cannot afford.
 */
"""


def emit():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return HEADER + "window.RV_BRAKE_LAWS = " + body + ";\n"


def main():
    want = emit()
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != want:
            print("DRIFT: assets/js/brakelawsdata.js is not what _data/state-brake-laws.json produces")
            print("      re-run: python3 scripts/build-brake-laws-data.py")
            raise SystemExit(1)
        n = len(json.loads(SRC.read_text(encoding="utf-8"))["states"])
        print("brake laws data matches the record (%d state(s))" % n)
        raise SystemExit(0)
    OUT.write_text(want, encoding="utf-8")
    n = len(json.loads(SRC.read_text(encoding="utf-8"))["states"])
    print("wrote %s (%d state(s), %d bytes)" % (OUT.relative_to(ROOT), n, len(want)))


if __name__ == "__main__":
    main()
