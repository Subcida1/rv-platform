#!/usr/bin/env python3
"""Emit assets/js/waterfilterdata.js from _data/water-filters.json.

WHY A GENERATOR RATHER THAN THE DATA IN THE TOOL'S OWN SCRIPT. The record for this tool is
larger than the ones beside it (every inline filter, every housing, every form factor, each with
the source document it came from), and the engine that walks it is small. Keeping the two in one
file means editing the engine means scrolling past the data, and it means a fact can be corrected
in the JSON and left stale in the JS. The coordinate tables on this site are built the same way
for the same reason: _data is the source, assets/js is the artifact, and --check proves the two
have not forked. scripts/test-water-filter.js checks the same thing from the other side.

Run:  python3 scripts/build-water-filter-data.py
      python3 scripts/build-water-filter-data.py --check
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "_data" / "water-filters.json"
OUT = ROOT / "assets" / "js" / "waterfilterdata.js"

HEAD = """/* GENERATED by scripts/build-water-filter-data.py from _data/water-filters.json.
 * Do not edit this file; edit the record and re-run the generator.
 *
 * THE ONE RULE THE SHAPE ENFORCES: a value reaches a reader only from a maker's own document or
 * a maker's own domain. Anything the research found only in retailer copy stays in `retailer_only`
 * and is never printed, and an attribute no maker publishes is named in `not_published` so the
 * tool can say so rather than leave a blank that reads like an omission.
 */
"""


def js(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"), sort_keys=False)


def build():
    rec = json.loads(SRC.read_text(encoding="utf-8"))
    body = ("window.RV_WATER_FILTERS = " + js(rec) + ";\n")
    return HEAD + body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the artifact does not match the record")
    a = ap.parse_args()
    want = build()
    if a.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != want:
            print("FAIL: %s is not what %s produces" % (OUT.relative_to(ROOT), SRC.relative_to(ROOT)))
            print("      run: python3 scripts/build-water-filter-data.py")
            return 1
        print("water filter data: %s matches the record" % OUT.relative_to(ROOT))
        return 0
    OUT.write_text(want, encoding="utf-8")
    rec = json.loads(SRC.read_text(encoding="utf-8"))
    counts = {k: len(v) for k, v in rec.items() if isinstance(v, (list, dict))}
    print("wrote %s (%d bytes)" % (OUT.relative_to(ROOT), len(want)))
    print("  " + ", ".join("%s %d" % (k, n) for k, n in counts.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
