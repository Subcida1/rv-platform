/* Holds _data/state-brake-laws.json, assets/js/brakelawsdata.js and the tool page to the same
 * facts, so the three cannot drift.
 *
 * THE RULE THIS FILE EXISTS TO PROTECT: a threshold reaches a reader only with the section it
 * came from and the URL it was read at. A guessed limit is the one failure this tool cannot
 * afford, because a number that is too high tells somebody to tow without brakes. So the checks
 * below are mostly about what is NOT allowed on the page, not about what is.
 *
 * Usage: node scripts/test-state-brake-laws.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA = JSON.parse(fs.readFileSync(path.join(ROOT, '_data/state-brake-laws.json'), 'utf8'));
const GEN = fs.readFileSync(path.join(ROOT, 'assets/js/brakelawsdata.js'), 'utf8');
const SRC = fs.readFileSync(path.join(ROOT, 'assets/js/brakelaws.js'), 'utf8');
const PAGE = fs.readFileSync(path.join(ROOT, 'tools/state-trailer-brake-laws.html'), 'utf8');

let failed = 0;
function check(name, ok, detail) {
  if (ok) { console.log('  ok   ' + name); return; }
  failed++;
  console.log('  FAIL ' + name + (detail ? '  <- ' + detail : ''));
}

console.log('state trailer brake laws');

/* ---- the record itself ---- */
check('the record parses and carries states', Array.isArray(DATA.states) && DATA.states.length > 0);
check('every state has a section and a URL to read it at',
  DATA.states.every(s => s.section && s.url),
  DATA.states.filter(s => !s.section || !s.url).map(s => s.code).join(','));
check('every state has a threshold or says there is none',
  DATA.states.every(s => s.threshold !== undefined),
  DATA.states.filter(s => s.threshold === undefined).map(s => s.code).join(','));
check('a state with a threshold always carries the quote it came from',
  DATA.states.every(s => s.threshold === null || s.quote || s.quoteNote),
  DATA.states.filter(s => s.threshold !== null && !s.quote && !s.quoteNote).map(s => s.code).join(','));
check('every state code appears in the full state list',
  DATA.states.every(s => DATA.allStates.some(p => p[0] === s.code)),
  DATA.states.filter(s => !DATA.allStates.some(p => p[0] === s.code)).map(s => s.code).join(','));
check('the coverage count is the number of states actually read',
  DATA.coverage.covered === DATA.states.length,
  DATA.coverage.covered + ' vs ' + DATA.states.length);
check('the missing list is the difference between the two',
  DATA.coverage.missing.length === DATA.coverage.total - DATA.coverage.covered);
check('no state is listed twice', new Set(DATA.states.map(s => s.code)).size === DATA.states.length);

/* ---- the generated file is what the record produces ---- */
const body = JSON.stringify(DATA, null, 1).replace(/\n/g, '\n');
check('the generated data file declares the same number of states',
  (GEN.match(/"code":/g) || []).length === DATA.states.length,
  (GEN.match(/"code":/g) || []).length + ' vs ' + DATA.states.length);
check('the generated file carries the coverage block', /"coverage"/.test(GEN));
check('the generated file says it is generated', /GENERATED by scripts\/build-brake-laws-data\.py/.test(GEN));

/* ---- the page ---- */
check('the page loads the data file', /assets\/js\/brakelawsdata\.js/.test(PAGE));
check('the data file loads before the finder',
  PAGE.indexOf('brakelawsdata.js') < PAGE.indexOf('brakelaws.js'),
  'order matters: the finder reads the data on load');
check('the page has the state picker', /id="bl-state"/.test(PAGE));
check('the page has a result host that announces changes', /id="bl-result"[^>]*aria-live="polite"/.test(PAGE));
check('the page has the full table body', /id="bl-table"/.test(PAGE));

/* ---- what the page must NOT claim ---- */
check('the page does not promise a national threshold',
  !/national (limit|threshold|requirement) (of|is) \d/i.test(PAGE));
check('the page does not print a threshold for an unread state in the markup',
  !/id="bl-table">\s*<tr/.test(PAGE), 'the table is rendered from the record, not hand-written');
check('the page says a state without an entry has not been read',
  /not covered yet/.test(PAGE) && /not been read/.test(PAGE));

/* ---- the finder, driven over the record ---- */
function run(code) {
  const byId = {};
  /* The stub has to CAPTURE listeners, not swallow them. A no-op addEventListener meant the
     finder's change handler was never registered, so render() never ran and the first version of
     this test failed on an undefined result host rather than on anything about the tool. */
  const el = () => {
    const o = {
      value: '', checked: false, textContent: '', innerHTML: '', style: {},
      classList: { add() {}, remove() {}, toggle() {}, contains: () => false },
      removeAttribute() {}, setAttribute() {}, __h: {},
      addEventListener(t, f) { o.__h[t] = f; },
      fire(t) { if (o.__h[t]) o.__h[t](); },
    };
    return o;
  };
  const doc = {
    readyState: 'complete',
    getElementById: id => byId[id] || (byId[id] = el()),
    querySelector: () => null, querySelectorAll: () => [], addEventListener() {},
  };
  const sandbox = { console, document: doc, window: {}, setTimeout, clearTimeout, Date, Math };
  sandbox.window = sandbox; sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(GEN, sandbox, { filename: 'brakelawsdata.js' });
  vm.runInContext(SRC, sandbox, { filename: 'brakelaws.js' });
  const pick = byId['bl-state'] || el();
  pick.value = code;
  pick.fire('change');
  return {
    result: (byId['bl-result'] || el()).innerHTML,
    table: (byId['bl-table'] || el()).innerHTML,
    pick: pick.innerHTML,
  };
}

const ca = run('CA');
check('the picker offers every state', (ca.pick.match(/<option/g) || []).length === DATA.allStates.length + 1,
  (ca.pick.match(/<option/g) || []).length + ' options');
check('the picker marks the states with no entry', /not covered yet/.test(ca.pick));

const tx = run('TX');
check('a picked state renders its threshold', /4,500 lb gross/.test(tx.result), tx.result.slice(0, 120));
check('a picked state renders its section', /Texas Transportation Code 547\.401/.test(tx.result));
check('a state quoted from an agency says so', /Department of Public Safety/.test(tx.result));
check('a state with a breakaway rule renders it', /Breakaway/.test(tx.result));

const or_ = run('OR');
check('a state with no weight threshold says so', /No weight threshold/.test(or_.result));

const caR = run('CA');
check('a state with no quote says why rather than showing one', /refuses automated reads/.test(caR.result));

/* The unread state is READ FROM THE RECORD, not hardcoded. The first version named Alaska, and
   the day Alaska was added this check failed on a tool that was working correctly -- a test that
   goes stale the moment the data improves is a test that will be silenced rather than fixed. */
const unread = DATA.coverage.missing[0];
if (unread) {
  const ur = run(unread);
  check('an unread state says it is not covered rather than answering', /Not covered yet/.test(ur.result), unread);
  check('  and does not print a threshold for it', !/\d[\d,]*\s*lb/i.test(ur.result), unread);
} else {
  check('every state is covered, so there is no unread case to test', true);
}

const table = run('CA').table;
check('the table renders one row per state read', (table.match(/<tr>/g) || []).length === DATA.states.length,
  (table.match(/<tr>/g) || []).length + ' vs ' + DATA.states.length);
check('every table row links to the state it came from', (table.match(/href="https?:\/\//g) || []).length === DATA.states.length);

console.log(failed ? '\n' + failed + ' failure(s)' : '\nstate trailer brake laws: all checks passed');
process.exit(failed ? 1 : 0);
