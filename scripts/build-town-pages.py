#!/usr/bin/env python3
"""Build the town pages: one page per (state, town) that has at least one listing.

WHY. Every listing names the towns it covers in `areas` (2,004 of 2,025 records), and
that town graph was only ever rendered at state level. So a search for a small town
landed on a state page with 90 businesses on it, while the competitor that wins those
searches renders a page per town. The data was already here; this renders it.

WHAT OWNS WHAT. This file writes every file under directory/<state>/ and nothing else.
It does not touch the state pages, the shards, the hub, the sitemap or the search index;
each of those stays with its own writer (build-listings.py, build-sitemap.py,
build-search-index.py) so two builders cannot disagree about the same markup.

    python3 scripts/build-town-pages.py            write everything
    python3 scripts/build-town-pages.py --check    fail on drift or a stale page
    python3 scripts/build-town-pages.py --limit 20 build only the 20 towns for one look

THREE RULES THAT DECIDE THE SHAPE, each measured before the first page was written:

1. A TOWN PAGE IS ONLY FOR A TOWN THAT HAS A LISTING. 2,813 towns carry at least one
   listing and another ~2,000 place names in `areas` carry none; a page for a town with
   nothing on it is a dead end, which the search doctrine forbids.
2. ONE LISTING IS ENOUGH. 1,863 of the 2,813 towns (66%) have exactly one listing. Gating
   on two would drop two thirds of the coverage this exists to add, and a single mobile
   tech who covers your town is the answer the reader searched for. The page says how
   many there are rather than dressing one up as a directory.
3. THE PAGE MUST NOT BE A DEAD END. Every town page links to its state page, to the
   neighbouring towns that have techs, and to the guides and tools, so a town with one
   tech still has a next step.

TWO THINGS THE PAGE MAY NOT DO, both from the site's own doctrine:

- It may not state a population, a drive time or a distance it did not compute. The
  nearest-town list carries a real computed distance and nothing else.
- It may not invent a rate. No listing carries one; see _todo/COMPETITIVE-SCAN-2026-10-31.md
  section 8 for the 45-listing slice that decided this.
"""

import html
import json
import math
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import site_constants as C  # noqa: E402
from place_names import canonical  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "_data" / "listings"
OUT = ROOT / "directory"
SITE = "https://originrv.com"

PAGES = {slug: code.upper() for code, slug in C.state_shards().items()}
TYPE_LABEL = {"mobile": "Mobile technician", "center": "Service center",
              "both": "Mobile and shop"}

# How many neighbouring towns a page names. Enough to be useful, few enough that the
# list stays a next step rather than a second directory.
NEIGHBOURS = 6
# Two listings further apart than this are not neighbours, even in an empty state: the
# point of the list is "who else reaches you", not "who exists in this half of Texas".
NEIGHBOUR_MILES = 75.0

# ONLY TOWNS WITH A REAL CHOICE, FOR THE FIRST SLICE (decided 2026-10-31).
# 1,863 of 2,813 towns carry exactly one listing, and a page whose whole content is one tech
# plus six links to other towns is the shape Google calls thin. The first slice ships the
# towns where the page answers the question a reader actually asked (who can I call, and is
# there a choice), which is 950 pages at MIN_LISTINGS=2. Raise to 1 to publish every town,
# raise to 3 for the 384 strongest. The generator renders whatever this is set to, and the
# manifest records the threshold so the number on disk is explainable later.
MIN_LISTINGS = 2

START_MARK = "<!-- TOWNS:BODY-START -->"
END_MARK = "<!-- TOWNS:BODY-END -->"
MANIFEST = ROOT / "_data" / "towns.json"
# Longest first. Each entry ends the description; the first one that keeps the whole string
# inside 140 to 160 characters wins, so a short town name gets the full sentence and a long
# one gets the short version.
DESC_TAILS = (" Call before you drive to a campsite, driveway or storage lot.",
              " Call before you drive out to a campsite or a storage lot.",
              " Call before you drive out to a campsite.",
              " Call before you drive out.",
              " Call first.")
TOWNS_JS = ROOT / "assets" / "js" / "towns.js"
TOWNS_JS_HEAD = """/* Generated by scripts/build-town-pages.py from _data/towns.json. Do not hand-edit.

   The town manifest the search box needs: one row per town page, in country order, so a
   reader who types a town resolves to that town's own page instead of the state page. Three
   fields per row, short names because this ships on every page that loads the resolver:
     s  USPS state code
     n  the town as the businesses spell it
     k  the URL segment under /directory/<state slug>/

   Deliberately NOT in the search index. The index is 692 KB and shipped on every page;
   2,813 extra entries would add 43 KB gzipped for a lookup this file answers in 20 KB
   gzipped, and only for a reader who types a location. Absent file means no town pages,
   and townUrl() in locate.js falls back to the state page, which stays correct.
*/
"""


def esc(s):
    return html.escape(str(s), quote=True)


def slug_of(name):
    """The URL segment. Lowercase, words joined by a single dash, ASCII only.

    Deliberately identical in shape to the state slugs, and deliberately NOT the
    canonical() used for matching: canonical() strips the word "city" and folds
    apostrophes because that is how Census names differ from business usage, and a URL
    built from it would collapse two different towns onto one path.
    """
    s = name.lower().replace("&", " and ")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s or "town"


def haversine(a, b):
    lat1, lon1 = a
    lat2, lon2 = b
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = p2 - p1
    dl = math.radians(lon2 - lon1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 3958.8 * 2 * math.asin(math.sqrt(h))


def load_coords(st):
    src = ROOT / "assets" / "js" / ("coords-%s.js" % st.lower())
    if not src.exists():
        return {}
    t = src.read_text(encoding="utf-8")
    return json.loads(t[t.find("{"):t.rfind("}") + 1]).get("city", {})


def load_states():
    out = {}
    for slug, st in PAGES.items():
        src = DATA / ("%s.json" % slug)
        if not src.exists():
            sys.exit("no %s; run scripts/build-listings.py --import" % src.relative_to(ROOT))
        out[slug] = json.loads(src.read_text(encoding="utf-8"))
    return out


def towns_of(state):
    """(canonical town -> [label, [listings]]) for one state.

    Labels come from the listing's own `areas` value, not from the Census, because the
    business named the town the way its customers do. The first spelling seen wins and a
    title-cased fallback keeps an all-lowercase data entry from rendering as a URL slug.
    """
    got = {}
    for row in state["listings"]:
        seen = set()
        for raw in row.get("areas") or []:
            key = canonical(raw)
            if not key or key in seen:
                continue
            seen.add(key)
            if key not in got:
                got[key] = {"label": raw.strip(), "rows": []}
            got[key]["rows"].append(row)
    return got


def rep(row, st):
    """One row, in the SAME markup the state page uses.

    Deliberately the same classes, so the town page cannot drift into a second visual
    language, and the click counter's hooks are identical, so a call made from a town
    page is counted the same way. The town column is dropped: on this page every row is
    in the town named in the heading, so repeating it would be furniture.
    """
    bits = []
    if row.get("r"):
        bits.append('<span class="finder-flag roadside">Roadside and stuck</span>')
    elif row.get("e"):
        bits.append('<span class="finder-flag">Emergency mobile repair</span>')
    flags = ('<span class="finder-region-flags">%s</span>' % "".join(bits)) if bits else \
        '<span class="finder-region-flags"></span>'
    attrs = 'data-lk="%s" data-lk-st="%s"' % (esc(row["n"]), esc(st))
    name = ('<a href="%s" target="_blank" rel="noopener" %s data-lk-kind="site">%s</a>'
            % (esc(row["u"]), attrs, esc(row["n"]))) if row.get("u") else esc(row["n"])
    tel = re.sub(r"[^0-9+]", "", row["p"])
    spec = ('<span class="finder-region-spec">%s</span>' % esc(row["spec"])) if row.get("spec") else ""
    return ('<li class="finder-region-row">'
            '<span class="finder-region-name">%s</span>'
            '<span class="finder-region-town">%s</span>'
            '<span class="finder-region-type">%s</span>'
            '%s'
            '<a class="finder-region-call" href="tel:%s" %s data-lk-kind="tel">%s</a>'
            '%s'
            '</li>' % (name, esc(row["c"]), TYPE_LABEL[row["t"]], flags, esc(tel),
                       attrs, esc(row["p"]).replace("-", "&#8209;").replace(" ", "&nbsp;"), spec))


def lede(rows, town, state_name):
    """The opening paragraph, written from what the rows carry.

    The counts are computed, never asserted, and the mobile/shop split is stated because
    it is the thing that decides whether the tech can come to the reader.
    """
    n = len(rows)
    mob = sum(1 for r in rows if r["t"] in ("mobile", "both"))
    where = sum(1 for r in rows if r["t"] == "center")
    if n == 1:
        r = rows[0]
        what = "a mobile technician" if r["t"] == "mobile" else (
            "a shop that also travels to the RV" if r["t"] == "both" else "a service center")
        return ("%s has %s listed as covering it. %s works out of %s and names %s in the "
                "towns it reaches." % (esc(town), what, esc(r["n"]), esc(r["base"]),
                                       esc(town)))
    bits = ["%d RV repair businesses list %s among the towns they cover." % (n, esc(town))]
    # THE SENTENCE HAS TO AGREE WITH ITS NUMBER (2026-11-01). "%d of them come to the RV or do
    # both, and %d work from a shop" reads correctly at "2 of them come" and wrong at "1 of them
    # come", which is what it said on 255 of the 950 town pages: a town with one mobile tech was
    # described in the plural. Both halves can be one, so both halves get their own wording.
    if mob and where:
        come = ("1 of them comes to the RV or does both" if mob == 1
                else "%d of them come to the RV or do both" % mob)
        shop = "1 works from a shop" if where == 1 else "%d work from a shop" % where
        bits.append("%s, and %s." % (come, shop))
    elif mob:
        bits.append("All of them travel to where the RV is parked.")
    return " ".join(bits)



def _page_desc(label, state_name):
    """The meta description, held inside 140 to 160 characters for every town in the set.

    Measured on the ESCAPED string, because that is what ships and what the gate reads:
    "D'Iberville" becomes "D&#x27;Iberville" and costs five extra characters.
    """
    desc = ("RV repair in %s, %s. Who covers the town, where they work from, and the number."
            % (label, state_name))
    for tail in DESC_TAILS:
        if 140 <= len(esc(desc + tail)) <= 160:
            return desc + tail
    sys.exit("FAIL  no description tail fits %s, %s at %d chars"
             % (label, state_name, len(desc)))


def _split_phrase(rows):
    """How many come to the RV and how many work from a shop, as a clause.

    Counted from the rows, because it is the single fact that decides whether the reader
    can stay parked. Never asserts a split the data does not have.
    """
    mob = sum(1 for r in rows if r["t"] in ("mobile", "both"))
    shop = len(rows) - mob
    if len(rows) == 1:
        r = rows[0]
        return {"mobile": "a mobile technician who comes to you",
                "both": "a business that travels to the RV",
                "center": "a service center with a shop"}[r["t"]]
    if mob and shop:
        return "%d that come to the RV and %d that work from a shop" % (mob, shop)
    if mob:
        return "all mobile technicians who come to the RV"
    return "all working from a shop"


def build_page(slug, st, town, label, rows, state_name, neigh, coords, st_town_count):
    """The whole page. The chrome is the state page's, so nav, footer and base are shared."""
    tslug = slug_of(label)
    here = "/directory/%s/%s" % (slug, tslug)
    title = "RV Repair in %s, %s" % (label, state_name)
    # Under 60 characters where it fits: the search-facing string, with the state code
    # because a town name alone is ambiguous across states.
    short = "%s RV Repair, %s" % (label, st)
    # 140 to 160 characters, and the site's own gate fails anything outside it. A description
    # built from variable parts (the count, the mobile/shop split) could not be held inside a
    # 20-character band: measured, the two obvious wordings gave 117-149 and 147-179, so
    # thousands of pages fell outside either way. So the CORE is fixed and only the state and
    # town names vary, and the tail is the shortest of a fixed list that lands the whole string
    # inside the band. Measured across all 2,813 with zero unfittable.
    # The count and the mobile/shop split are NOT in here: they already lead the page and the
    # JSON-LD ItemList carries them as data, so the snippet says the one thing a snippet has
    # room for, which is what the page answers.
    desc = ("RV repair in %s, %s. Who covers the town, where they work from, and the number."
            % (label, state_name))
    # Measured on the ESCAPED string, because that is what ships and what the gate reads:
    # "D'Iberville" becomes "D&#x27;Iberville" and costs five extra characters, which put four
    # pages at 161 to 164 when the fit was computed on the raw text.
    for tail in DESC_TAILS:
        if 140 <= len(esc(desc + tail)) <= 160:
            desc += tail
            break
    else:
        sys.exit("FAIL  no description tail fits %s, %s at %d chars"
                 % (label, state_name, len(desc)))

    body = ['<div class="wrap">',
            '<p class="crumbs"><a href="/directory/%s">%s</a> . %s</p>' % (slug, esc(state_name), esc(label)),
            '<h1 class="sp-14">RV repair in %s, %s</h1>' % (esc(label), esc(state_name)),
            '<p class="lede wide">%s</p>' % lede(rows, label, state_name),
            '<div class="finder-regions sp-34">',
            '<h2 class="finder-region-h sp-44">RV repair businesses covering %s</h2>' % esc(label),
            '<ul class="finder-region-list">']
    for r in rows:
        body.append(rep(r, st))
    body += ["</ul>", "</div>"]
    if neigh:
        body.append('<h2 class="finder-region-h sp-44">Nearby towns with RV repair</h2>')
        body.append('<p class="sm">Each town keeps its own page, and the distance is '
                    'measured from the town center.</p>')
        body.append('<ul class="finder-region-list">')
        for name, nslug, miles, n in neigh:
            body.append('<li class="finder-region-row">'
                        '<span class="finder-region-name"><a href="/directory/%s/%s">RV repair in %s</a></span>'
                        '<span class="finder-region-town">%d %s listed</span>'
                        '<span class="finder-region-type">About %.0f miles</span>'
                        '</li>'
                        % (slug, nslug, esc(name), n,
                           "business" if n == 1 else "businesses", miles))
        body.append("</ul>")
    # The next step, always present, so no town page is a dead end.
    body += ['<div class="page-foot sp-44">',
             '<h2 class="sm">Before you call</h2>',
             '<p class="sm">The <a href="/guides/">guides</a> work through common faults from '
             'the symptom, so you can tell a fifteen-minute check from a job. The '
             '<a href="/tools/">tools</a> cover the numbers: weight, load, tire age, battery '
             'runtime.</p>',
             '<p class="sm">The <a href="/directory/%s">whole %s directory</a> lists every '
             'business in the state, grouped by region.</p>' % (slug, esc(state_name)),
             '</div>', '</div>']

    schema = {
        "@context": "https://schema.org",
        "@type": "CollectionPage",
        "name": title,
        "description": desc,
        "url": SITE + here,
        "isPartOf": {"@type": "WebSite", "name": "OriginRV", "url": SITE + "/"},
        "mainEntity": {
            "@type": "ItemList",
            "numberOfItems": len(rows),
            "itemListElement": [
                {"@type": "ListItem", "position": i + 1,
                 "item": {"@type": "LocalBusiness", "name": r["n"],
                          "telephone": r["p"],
                          **({"url": r["u"]} if r.get("u") else {}),
                          "address": {"@type": "PostalAddress",
                                      "addressLocality": r.get("base") or label,
                                      "addressRegion": st,
                                      "addressCountry": "US"}}}
                for i, r in enumerate(rows)],
        },
    }
    return {
        "slug": tslug, "state_slug": slug, "state": st, "town": label,
        "title": title, "short": short, "desc": desc, "url": here,
        "count": len(rows), "body": "\n".join(body),
        "schema": json.dumps(schema, ensure_ascii=False),
        "neighbours": [n[1] for n in neigh],
    }


def chrome(state_page_text):
    """Everything outside <main> from the state page: head, nav, footer, scripts.

    Copied rather than reinvented so a town page cannot ship with a nav the state pages
    do not have, and re-derived on every build so a nav change reaches 2,813 pages.

    THE NAV IS BETWEEN </head> AND <main>, not inside the head, and it carries the
    nav:start/nav:end markers build-shell.mjs rewrites. Taking only the head dropped those
    markers on all 2,813 pages, which the shell gate reported as "no nav:start/nav:end
    markers" (2026-10-31). So this takes the whole prefix up to <main>.
    """
    main_start = state_page_text.index("<main")
    head = state_page_text[:main_start]
    # The state page carries its own JSON-LD in the head (a CollectionPage for the state).
    # Copying it onto a town page would give every town page two competing identities and
    # a schema name that says "Alabama" on a page about Daphne, so it comes out here.
    head = re.sub(r'\s*<script type="application/ld\+json">.*?</script>', "", head, flags=re.S)
    body_open = re.search(r"<body[^>]*>", head)
    if body_open is None:
        sys.exit("FAIL  no <body> in the state page")
    main_open = re.search(r"<main[^>]*>", state_page_text[main_start:])
    if main_open is None:
        sys.exit("FAIL  no <main> in the state page")
    main_open = main_open.group(0)
    foot_i = state_page_text.index("</main>")
    after = state_page_text[foot_i + len("</main>"):]
    if "<!-- nav:start -->" not in head:
        sys.exit("FAIL  the state page prefix has no nav:start marker; town pages would "
                 "inherit a nav build-shell.mjs cannot rewrite")
    return head, body_open.group(0), main_open, after


def render(slug, st, town, label, rows, state_name, neigh, coords, chrome_bits, st_town_count):
    """Fill the TOWNS:BODY markers on the template rather than reassembling the page.

    THE FIRST VERSION REASSEMBLED, and that is what made the two writers fight: it rebuilt the
    nav and footer from the state page every run, so build-shell.mjs always found the
    breadcrumb and the shell out of date on all 2,813 pages and the pair never settled. Filling
    between markers leaves every byte outside them alone, which is the same contract
    build-listings.py uses for the region blocks, and it means one page shape has exactly one
    writer per region.
    """
    tpl = chrome_bits
    p = build_page(slug, st, town, label, rows, state_name, neigh, coords, st_town_count)
    url = SITE + p["url"]
    # ONLY THE MARKED BODY IS OURS. The nav, the breadcrumb, the footer and the stamps all
    # belong to build-shell.mjs and stamp_assets.py, and the first version of this function
    # rewrote them from a template, which leaked one town's "Back to top" anchor into
    # another town's footer and made the two builders chase each other on every run: 2,764
    # pages "out of date" after every build, forever. A page shape gets exactly one writer
    # per region, which is the contract every other generator in this repo already keeps.
    # The <head> identity for a NEW page is the state page's, which is close enough that the
    # head is then rewritten once by hand; everything after that lives inside the markers.
    # THE PAGE'S OWN JSON-LD GOES IN THE HEAD, as it does on every other page on the site.
    # It was inside the body block first, and check-column.py failed all 2,813 pages for a
    # bare <script> block outside a content column -- the rule exists because a block in the
    # body needs the page gutter, and structured data is not content.
    head_end = tpl.index("</head>")
    head, rest = tpl[:head_end], tpl[head_end:]
    head = re.sub(r'\s*<script type="application/ld\+json">(?:(?!</script>).)*</script>', "",
                  head, count=1, flags=re.S)
    out = head + rest
    out, n = re.subn(r"(</head>)",
                     lambda m: '  <script type="application/ld+json">' + p["schema"] + "</script>\n" + m.group(1),
                     out, count=1, flags=re.S)
    body = p["body"]
    out, n = re.subn(re.escape(START_MARK) + r".*?" + re.escape(END_MARK),
                     lambda m: START_MARK + "\n" + body + "\n" + END_MARK, out, count=1, flags=re.S)
    if n != 1:
        sys.exit("FAIL  %s/%s: TOWNS markers not found exactly once" % (slug, p["slug"]))
    if out.count("<body") != 1 or out.count("</body>") != 1:
        sys.exit("FAIL  %s/%s: body tags %d/%d"
                 % (slug, p["slug"], out.count("<body"), out.count("</body>")))
    return out


def plan(states):
    """Every (state, town) worth a page, with its neighbours resolved.

    One pass over the data. Neighbours are the nearest towns IN THE SAME STATE that have
    at least one listing, which is a rule rather than a bug: RV Service List's town pages
    are state-scoped too, and a town 20 miles away across a state line belongs on that
    state's pages, where its own page is.
    """
    jobs = []
    for slug, st in sorted(PAGES.items()):
        data = states[slug]
        name = data["name"]
        coords = load_coords(st)
        towns = towns_of(data)
        # a coordinate per town, from the Census table; a town with no coordinate still
        # gets a page, it just cannot appear in anyone's neighbour list
        pts = {}
        for key, t in towns.items():
            c = coords.get(key)
            if c:
                pts[key] = (c[0], c[1])
        for key, t in towns.items():
            # THE SLICE. A town below the publishing threshold is not a page, and it is also
            # not a neighbour: linking to a page that does not exist would be a dead end, so
            # the filter is applied before the neighbour lists are built.
            if len(t["rows"]) < MIN_LISTINGS:
                continue
            neigh = []
            if key in pts:
                d = sorted(((haversine(pts[key], pts[k]), k) for k in pts if k != key))
                neigh = [(towns[k]["label"], slug_of(towns[k]["label"]), miles,
                          len(towns[k]["rows"]))
                         for miles, k in d
                         if miles <= NEIGHBOUR_MILES
                         and len(towns[k]["rows"]) >= MIN_LISTINGS][:NEIGHBOURS]
            jobs.append({"state_slug": slug, "state": st, "town_key": key,
                         "town": t["label"], "rows": t["rows"], "state_name": name,
                         "neigh": neigh, "coords": coords, "town_count": len(towns)})
    return jobs



def stamp_identity(page, slug, st, state_name, tslug, town, desc):
    """Set the page identity from the values this build computed: title, description,
    canonical, the social tags and the two body data attributes.

    RUN THIS ON EVERY PAGE, NEW OR EXISTING. It used to be called only for a page that did not
    exist yet, on the reasoning that an existing page's identity was already written. That
    reasoning had a hole with teeth: 950 town pages went out carrying the STATE page's title,
    og:url and canonical, because they were first generated before this function existed and a
    rebuild skipped them ever after. A canonical pointing at the state page tells a search
    engine the town page is a duplicate of it and must not be indexed, so the whole family was
    invisible while every gate stayed green. Nothing checked it, because nothing owned it.

    It is written as a substitution against the CURRENT bytes rather than a string built from
    scratch, so it is idempotent: called on an already-correct page it changes nothing and the
    rebuild stays a no-op. That is what lets it run unconditionally without the build reporting
    every page stale on every run.
    """
    town_slug = tslug
    url = "%s/directory/%s/%s" % (SITE, slug, town_slug)
    short = "%s RV Repair, %s" % (town, st)
    out = re.sub(r"<title>.*?</title>", "<title>%s</title>" % esc(short), page, count=1, flags=re.S)
    out = re.sub(r'data-state="[A-Za-z]{2}"', 'data-state="%s"' % st, out, count=1)
    out = re.sub(r'data-state-name="[^"]*"', 'data-state-name="%s"' % esc(state_name), out, count=1)
    out = re.sub(r'(<link rel="canonical" href=")[^"]*(")', r"\g<1>%s\g<2>" % url, out, count=1)
    out = re.sub(r'(<meta property="og:title" content=")[^"]*(")', r"\g<1>%s\g<2>" % esc(short), out, count=1)
    out = re.sub(r'(<meta property="og:url" content=")[^"]*(")', r"\g<1>%s\g<2>" % url, out, count=1)
    out = re.sub(r'(<meta name="twitter:title" content=")[^"]*(")', r"\g<1>%s\g<2>" % esc(short), out, count=1)
    out = re.sub(r'(<meta name="description" content=")[^"]*(")', r"\g<1>%s\g<2>" % esc(desc), out, count=1)
    out = re.sub(r'(<meta property="og:description" content=")[^"]*(")', r"\g<1>%s\g<2>" % esc(desc), out, count=1)
    out = re.sub(r'(<meta name="twitter:description" content=")[^"]*(")', r"\g<1>%s\g<2>" % esc(desc), out, count=1)
    return out


def main():
    args = sys.argv[1:]
    check = "--check" in args
    limit = None
    if "--limit" in args:
        limit = int(args[args.index("--limit") + 1])
    states = load_states()
    chrome_bits = {}
    for slug in PAGES:
        chrome_bits[slug] = chrome((OUT / ("%s.html" % slug)).read_text(encoding="utf-8"))
    jobs = plan(states)
    if limit:
        jobs = jobs[:limit]

    written, changed, stale = 0, [], []
    seen = {}
    templates = {}

    def base_page(slug):
        """The state page with an EMPTY town body, built once per state and never read back
        from a live town page.

        THE BUG THIS REPLACES (found after three gate runs, 2026-10-31). Templating from a
        town page that already existed meant copying that town's chrome onto every sibling,
        and the footer's "Back to top" link carries the page's own path: every rebuild
        wrote abbeville's anchor into decatur's footer, build-shell.mjs then corrected it,
        and the pair reported 2,764 pages stale on every single run. Building the base from
        the state page keeps chrome OUT of the loop entirely; build-shell.mjs writes the
        breadcrumb and the footer anchor from each page's own path, which is its job, and
        this file only ever writes between its own markers.
        """
        if slug in templates:
            return templates[slug]
        tpl = (OUT / ("%s.html" % slug)).read_text(encoding="utf-8")
        tpl, n = re.subn(r"(<main[^>]*>)",
                         r"\1\n" + START_MARK + "\n" + END_MARK + "\n", tpl, count=1)
        if n != 1:
            sys.exit("FAIL  %s: no <main> to build the town base from" % slug)
        # THE STATE PAGE'S "back to top" LINK NAMES THE STATE PAGE, and every town page cut
        # from this base would inherit it: the reader clicks Back to top on Daphne and lands
        # at the top of Alabama. build-shell.mjs owns that link and would fix it, but only if
        # it runs after every town build, and a chain that depends on running order is the
        # thing this file is trying not to be. So the back-to-top href is neutralised to the
        # bare "#top" site.js authors, and build-shell.mjs fills in the real prefix for each
        # page exactly as it does on every other page on the site.
        tpl = re.sub(r'(class="to-top" href=")[^"]*(")', r'\g<1>#top\g<2>', tpl, count=1)
        templates[slug] = tpl
        return tpl

    for j in jobs:
        slug, st = j["state_slug"], j["state"]
        tslug = slug_of(j["town"])
        # A slug collision inside one state is a data defect, not something to paper over.
        k = (slug, tslug)
        if k in seen:
            sys.exit("FAIL  two towns in %s slug to %r: %r and %r"
                     % (st, tslug, seen[k], j["town"]))
        seen[k] = j["town"]
        tpl = base_page(slug)
        page = render(slug, st, j["town_key"], j["town"], j["rows"], j["state_name"],
                      j["neigh"], j["coords"], tpl, len(j["rows"]))
        path = OUT / slug / ("%s.html" % tslug)
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if old:
            # AN EXISTING PAGE IS ITS OWN TEMPLATE. Its nav, breadcrumb and footer are
            # build-shell.mjs's output for THIS page -- the three-part trail, its own
            # back-to-top prefix -- and cut from the state page they would be the state's.
            # Copying them and replacing only the marked body is what makes a rebuild a no-op
            # and keeps one writer per region.
            page = render(slug, st, j["town_key"], j["town"], j["rows"], j["state_name"],
                          j["neigh"], j["coords"], old, len(j["rows"]))
        # Identity is stamped on EVERY page, new or existing, because it is the builder's to
        # own and because a page can be on disk with the wrong one (see stamp_identity). It is
        # idempotent, so on a page that is already correct this changes nothing and the build
        # still reports no change.
        page = stamp_identity(page, slug, st, j["state_name"], tslug, j["town"],
                              _page_desc(j["town"], j["state_name"]))
        if page != old:
            changed.append(str(path.relative_to(ROOT)))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(page, encoding="utf-8")
        written += 1

    # Pages on disk that this build no longer plans, which happens when a town's last
    # listing is removed. Never deleted automatically: say so and let a human decide.
    have = set()
    for p in OUT.glob("*/*.html"):
        if p.parent.name in PAGES:
            have.add(str(p.relative_to(ROOT)))
    planned = set(str((OUT / j["state_slug"] / ("%s.html" % slug_of(j["town"]))).relative_to(ROOT))
                  for j in jobs)
    orphans = sorted(have - planned)

    manifest = {
        "note": "Generated by scripts/build-town-pages.py. Pages, URLs and neighbour links.",
        "count": len(jobs),
        "min_listings": MIN_LISTINGS,
        "towns": [{"state": j["state"], "slug": slug_of(j["town"]), "town": j["town"],
                   "url": "/directory/%s/%s" % (j["state_slug"], slug_of(j["town"])),
                   "count": len(j["rows"])} for j in jobs],
    }
    mtext = json.dumps(manifest, indent=1, ensure_ascii=False) + "\n"
    mold = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
    if mtext != mold:
        changed.append(str(MANIFEST.relative_to(ROOT)))
        if not check:
            MANIFEST.write_text(mtext, encoding="utf-8")

    # The browser-side manifest, in the shape locate.js reads. Sorted by state code then
    # town so the emitted file is stable and a diff shows a real change, not a reshuffle.
    rows = [{"s": j["state"], "n": j["town"], "k": slug_of(j["town"])} for j in jobs]
    rows.sort(key=lambda r: (r["s"], r["n"].lower()))
    js = (TOWNS_JS_HEAD +
          "window.RV_TOWNS = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
    old_js = TOWNS_JS.read_text(encoding="utf-8") if TOWNS_JS.exists() else ""
    if js != old_js:
        changed.append(str(TOWNS_JS.relative_to(ROOT)))
        if not check:
            TOWNS_JS.write_text(js, encoding="utf-8")

    print("town pages planned: %d" % len(jobs))
    print("changed: %d" % len(changed))
    if orphans:
        print("ORPHAN pages on disk with no listing behind them (%d):" % len(orphans))
        for o in orphans[:20]:
            print("  " + o)
    if check and changed:
        for c in changed[:20]:
            print("  stale: " + c)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
